	public static void registerSounds(RegisterEvent event) {
		event.register(Registries.SOUND_EVENT, helper -> events.forEach(ev -> helper.register(ev.getLocation(), ev)));
	}

	private static SoundEvent createSoundEvent(String name) {
		SoundEvent event = SoundEvent.createVariableRangeEvent(new ResourceLocation(Techguns.MODID, name));
		events.add(event);
		return event;
	}
